const assert=require('node:assert/strict');
const {SynchronizedSession}=require('../../static/js/netplay/synchronized.js');
function packet(start,count,through){return {epoch:0,start,count,through,data:Buffer.alloc(count*16).toString('base64')};}
let now=0;const sent=[],errors=[];
const s=new SynchronizedSession({socket:{emit:(name,data)=>sent.push({name,data})},game:{tickRate:60},epoch:0,players:2,slot:null,spectator:true,clock:()=>now,onFailure:e=>errors.push(e)});
let ticks=0;s.bind({step:()=>ticks++,setReplaying(){}});s.start();
s.receive(packet(1,600,2000),true);
for(let i=0;i<10;i++)s.receive(packet(2001+i,1,2001+i));
assert.equal(sent.filter(e=>e.name==='sync_replay').length,1,'Live traffic cannot flood the replay buffer');
for(let i=0;i<600;i++)s.advance();
assert.equal(ticks,600);assert.equal(s.rows.size,0);
assert.equal(sent.filter(e=>e.name==='sync_replay').length,2);
s.receive(packet(601,600,2010),true);
for(let i=0;i<600;i++)s.advance();
s.receive(packet(1201,600,2010),true);
for(let i=0;i<600;i++)s.advance();
s.receive(packet(1801,210,2010),true);
for(let i=0;i<210;i++)s.advance();
assert.equal(ticks,2010);assert.ok(sent.some(e=>e.name==='sync_ready'));
s.receiveLive({epoch:0,through:2010});s.receiveLive({epoch:0,through:2010});
assert.equal(sent.filter(e=>e.name==='sync_input').length,0);
s.suspendTransport();assert.equal(s.advance(),false);
s.resumeTransport({epoch:0});assert.equal(s.live,false);assert.equal(s.frame,2010);
assert.deepEqual(errors,[]);
s.dispose();console.log('Bounded catch-up under live traffic, ordered replay, spectator input isolation and reconnect passed.');

// A hidden tab releases its controller without destroying the native engine.
const messages=[];
const player=new SynchronizedSession({socket:{emit:(name,data)=>messages.push({name,data})},game:{tickRate:60},epoch:0,players:2,slot:1,spectator:false,clock:()=>now,onFailure:e=>errors.push(e)});
player.bind({step(){},setReplaying(){},sampleInput:()=>({buttons:0,moveX:0,moveY:0,lookX:0,lookY:0}),hash:()=>0});
player.start();player.receive(packet(1,0,0),true);player.receiveLive({epoch:0,through:0});
player.setBackground(true);
assert.equal(messages.at(-1).name,'sync_pause');
const hiddenCount=messages.length;
player.receive(packet(1,600,600),true);player.receiveLive({epoch:0,through:600});
assert.equal(player.advance(),false);assert.equal(player.rows.size,0);
assert.equal(messages.length,hiddenCount,'In-flight responses cannot reactivate a hidden seat');
player.suspendTransport();player.resumeTransport({epoch:0});
assert.equal(messages.length,hiddenCount,'Reconnect while hidden must stay inactive');
player.setBackground(false);assert.equal(messages.at(-1).name,'sync_replay');
player.receiveLive({epoch:0,through:600});assert.equal(player.live,false,'Stale activation before fresh history must be ignored');
player.receive(packet(1,600,600),true);
for(let i=0;i<600;i++)player.advance();
assert.equal(player.frame,600);assert.equal(player.failed,false);
player.receiveLive({epoch:0,through:600});assert.equal(player.live,true);
assert.equal(messages.at(-1).name,'sync_input');
player.suspendTransport();const received=player.received;
player.receive(packet(601,1,601));player.receiveLive({epoch:0,through:601});
assert.equal(player.received,received);assert.equal(player.live,false);
assert.deepEqual(errors,[]);player.dispose();
console.log('Hidden-tab release, retained replay, stale-response isolation and hidden reconnect passed.');
